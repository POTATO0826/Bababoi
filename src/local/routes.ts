// Routes the WareOrb server adds in local presentation mode (WAREORB_LOCAL_DEMO=1). Bound to 127.0.0.1.
import { timingSafeEqual } from "node:crypto";
import { ConvexHttpClient } from "convex/browser";
import type { ToolDefinition } from "@earendil-works/pi-coding-agent";
import { api } from "../../convex/_generated/api";
import { LOCAL_DEMO_PRESENTER } from "../domain/local-demo";
import { agentStatus as realAgentStatus, readDeliveryEvidence as realRead, runAnalystTurn as realTurn, type AgentEvent, type AgentStatus, type ReadInput } from "./agent";
import { mintDemoToken } from "./demo-identity";
import { loopbackUrl } from "./isolation";
import { warehouseTools, type Snapshot } from "./warehouse-tools";

export interface LocalDemoConfig {
  port: number;
  convexUrl: string;
  /** Expected local Convex port; the URL must match it exactly. */
  convexPort?: number;
  privateJwk: string;
  agentSecret: string;
}

/** The agent operations the routes use; tests replace them with labelled mocks. */
export interface AgentOps {
  agentStatus(): Promise<AgentStatus>;
  runAnalystTurn(sessionId: string, text: string, tools: () => ToolDefinition[], emit: (e: AgentEvent) => void, signal?: AbortSignal): Promise<void>;
  readDeliveryEvidence(input: ReadInput): Promise<{ model: string; draft: unknown } | { error: string }>;
  /** Fresh ledger snapshot for the warehouse tools. */
  snapshot?: () => Promise<Snapshot | null>;
}

const noStore = { "Cache-Control": "no-store" };
const deny = (status: number, error: string) => Response.json({ error }, { status, headers: noStore });
/** SSE comment line keeping the connection busy while the model thinks. */
const HEARTBEAT_MS = 8_000;

export function localDemoRoutes(cfg: LocalDemoConfig, ops: AgentOps = { agentStatus: realAgentStatus, runAnalystTurn: realTurn, readDeliveryEvidence: realRead }) {
  // Never send the presenter's bearer token anywhere but this computer's Convex backend.
  const convexUrl = loopbackUrl(cfg.convexUrl, "BUN_PUBLIC_CONVEX_URL", cfg.convexPort);
  if (!/^[0-9a-f]{64}$/.test(cfg.agentSecret)) throw new Error("WAREORB_LOCAL_AGENT_SECRET must be the 64-character hex secret generated by `bun run demo`.");
  const hosts = new Set([`127.0.0.1:${cfg.port}`, `localhost:${cfg.port}`]);
  /** Only this page may use the presenter's identity: blocks other sites and DNS rebinding. */
  const fromThisApp = (req: Request) => {
    if (!hosts.has(req.headers.get("host") ?? "")) return false;
    const origin = req.headers.get("origin");
    if (!origin) return req.method === "GET";
    try { return hosts.has(new URL(origin).host); } catch { return false; }
  };
  const fromBackend = (req: Request) => {
    const given = Buffer.from(req.headers.get("authorization") ?? "");
    const expected = Buffer.from(`Bearer ${cfg.agentSecret}`);
    return given.length === expected.length && timingSafeEqual(given, expected);
  };
  /** The agent reads through the same authorised query as the presenter's screen. */
  const snapshot = ops.snapshot ?? (async () => {
    const client = new ConvexHttpClient(convexUrl);
    client.setAuth((await mintDemoToken(cfg.privateJwk, LOCAL_DEMO_PRESENTER, 300)).token);
    return await client.query(api.ledger.snapshot, { since: 0 });
  });

  return {
    "/api/demo/token": {
      GET: async (req: Request) => {
        if (!fromThisApp(req)) return deny(403, "Local presentation identity is only available to this app");
        return Response.json(await mintDemoToken(cfg.privateJwk, LOCAL_DEMO_PRESENTER), { headers: noStore });
      },
    },
    "/api/agent/status": {
      GET: async (req: Request) => (fromThisApp(req) ? Response.json(await ops.agentStatus(), { headers: noStore }) : deny(403, "Forbidden")),
    },
    "/api/agent/chat": {
      POST: async (req: Request) => {
        if (!fromThisApp(req) || !req.headers.get("content-type")?.startsWith("application/json")) return deny(403, "Forbidden");
        const body = (await req.json().catch(() => null)) as { sessionId?: unknown; text?: unknown } | null;
        const sessionId = typeof body?.sessionId === "string" && /^[\w-]{8,64}$/.test(body.sessionId) ? body.sessionId : null;
        const text = typeof body?.text === "string" ? body.text.trim() : "";
        if (!sessionId || !text || text.length > 2000) return deny(400, "A session id and a 1–2000 character question are required");
        const encoder = new TextEncoder();
        const abort = new AbortController();
        req.signal?.addEventListener("abort", () => abort.abort(), { once: true });
        let closed = false;
        let heartbeat: ReturnType<typeof setInterval> | undefined;
        const stream = new ReadableStream<Uint8Array>({
          async start(controller) {
            const send = (chunk: string) => {
              if (closed) return;
              try { controller.enqueue(encoder.encode(chunk)); } catch { closed = true; }
            };
            const emit = (e: AgentEvent) => send(`data: ${JSON.stringify(e)}\n\n`);
            heartbeat = setInterval(() => send(": keep-alive\n\n"), HEARTBEAT_MS);
            try { await ops.runAnalystTurn(sessionId, text, () => warehouseTools(snapshot), emit, abort.signal); }
            catch (e) { emit({ type: "error", message: e instanceof Error ? e.message : "The agent failed" }); }
            finally {
              clearInterval(heartbeat);
              if (!closed) { closed = true; try { controller.close(); } catch { /* already closed */ } }
            }
          },
          cancel() {
            // The browser stopped reading (Stop button, closed tab): stop the model too.
            closed = true;
            clearInterval(heartbeat);
            abort.abort();
          },
        });
        return new Response(stream, { headers: { ...noStore, "Content-Type": "text/event-stream; charset=utf-8", "X-Accel-Buffering": "no" } });
      },
    },
    "/internal/extract-receipt": {
      POST: async (req: Request) => {
        if (!hosts.has(req.headers.get("host") ?? "") || !fromBackend(req)) return deny(401, "Unauthorised");
        const body = (await req.json().catch(() => null)) as Partial<ReadInput> | null;
        if (!body || !Array.isArray(body.catalogue) || !Array.isArray(body.evidence) || body.evidence.length > 20) return deny(400, "Invalid reading request");
        const result = await ops.readDeliveryEvidence({ catalogue: body.catalogue.slice(0, 500), evidence: body.evidence });
        if ("error" in result) return deny(422, result.error);
        return Response.json({ ...(result.draft as object), model: result.model }, { headers: noStore });
      },
    },
  };
}
