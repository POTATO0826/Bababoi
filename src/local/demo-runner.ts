// The local presentation start-up (`bun run demo`). All process, network and file access goes through
// `DemoDeps` so tests can prove that a cloud selector stops everything before any write or request.
import { randomBytes } from "node:crypto";
import { LOCAL_DEMO_PRESENTER, localDemoTokenIdentifier } from "../domain/local-demo";
import { generateDemoKeys, mintDemoToken } from "./demo-identity";
import { childEnv, demoPorts, IsolationError, loopbackUrl, localTarget, parseEnvFile, preflight, type DemoPorts } from "./isolation";

export interface LongProcess {
  kill(): void;
  exited: Promise<number>;
}

export interface DemoDeps {
  root: string;
  ambient: Record<string, string | undefined>;
  argv: readonly string[];
  /** Read a project file (relative to root); null when absent. */
  read(file: string): string | null;
  /** Write a private project file (mode 0600). */
  writePrivate(file: string, text: string): void;
  /** Run a finite command. */
  run(cmd: string[], env: Record<string, string>): Promise<{ code: number; output: string }>;
  /** Start a long-running command; `log` names a project file for its output, else it inherits stdio. */
  start(cmd: string[], env: Record<string, string>, log?: string): LongProcess;
  fetch(url: string, init: RequestInit): Promise<Response>;
  /** Is this TCP port free on 127.0.0.1? */
  portFree(port: number): Promise<boolean>;
  /** Directory holding a Node.js 20, 22 or 24 binary for the local backend's "use node" actions. */
  convexNodeDir(): string;
  /** Write a 0600 temporary file, pass its path to `use`, then delete it. */
  withSecretFile<T>(text: string, use: (path: string) => Promise<T>): Promise<T>;
  log(message: string): void;
  sleep(ms: number): Promise<void>;
  /** Agent provider state, without calling the provider. */
  agentStatus(): Promise<{ ready: boolean; provider?: string; model?: string; subscription?: boolean; reason?: string }>;
}

export class DemoError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "DemoError";
  }
}

const KEYS = ["WAREORB_LOCAL_DEMO_PRIVATE_JWK", "WAREORB_LOCAL_DEMO_JWKS", "WAREORB_LOCAL_AGENT_SECRET"] as const;
/** Variables the operator may set for the agent; passed to the WareOrb server process only. */
const AGENT_PASS = ["WAREORB_AGENT_MODEL", "PI_CODING_AGENT_DIR", "ANTHROPIC_API_KEY", "OPENAI_API_KEY"] as const;

function appendEnv(current: string | null, entries: Record<string, string>): string {
  const kept = (current ?? "").split("\n").filter((l) => !Object.keys(entries).some((k) => l.startsWith(`${k}=`)));
  while (kept.length && !kept.at(-1)!.trim()) kept.pop();
  return [...kept, "", "# WareOrb local demo (generated by scripts/demo.ts; private to this computer, never commit)", ...Object.entries(entries).map(([k, v]) => `${k}='${v}'`), ""].join("\n");
}

type CallResult = { status: "success"; value: unknown } | { status: "error"; errorMessage: string; errorData?: unknown };

export interface RunningDemo {
  ports: DemoPorts;
  convexUrl: string;
  siteUrl: string;
  webUrl: string;
  /** Resolves when the web server exits (absent with --setup-only). */
  web?: Promise<number>;
  stop(): void;
}

/** Start (or, with --setup-only, prepare) the local demo. Throws IsolationError/DemoError with an actionable message. */
export async function runDemo(d: DemoDeps): Promise<RunningDemo> {
  const reset = d.argv.includes("--reset");
  const setupOnly = d.argv.includes("--setup-only");

  // 1. Isolation: every source the Convex CLI reads, the ports, then Node — before anything is written or started.
  const ports = demoPorts(d.ambient);
  const pre = preflight({ ambient: d.ambient, envLocal: d.read(".env.local"), dotEnv: d.read(".env"), ports });
  if (pre.droppedAmbient.length) d.log(`Ignoring ${pre.droppedAmbient.join(", ")} from your shell: the demo never passes cloud deployment selectors to Convex.`);
  const nodeDir = d.convexNodeDir();
  for (const [name, port, variable] of [["WareOrb", ports.web, "WAREORB_DEMO_PORT"], ["local Convex", ports.convex, "WAREORB_CONVEX_PORT"], ["local Convex HTTP", ports.convexSite, "WAREORB_CONVEX_SITE_PORT"]] as const) {
    if (!(await d.portFree(port))) throw new DemoError(`Port ${port} (${name}) is already in use on 127.0.0.1. Stop the other program or choose another port, e.g. ${variable}=${port + 10} bun run demo.`);
  }
  const agentUrl = loopbackUrl(`http://127.0.0.1:${ports.web}`, "Local agent URL", ports.web);
  const cliEnv = childEnv(d.ambient, { PATH: `${nodeDir}:${d.ambient.PATH ?? ""}`, CONVEX_AGENT_MODE: "anonymous" });
  const localFlags = ["--local-cloud-port", String(ports.convex), "--local-site-port", String(ports.convexSite)];
  const convex = async (args: string[], { allowFail = false } = {}) => {
    const r = await d.run(["bunx", "convex", ...args], cliEnv);
    const output = r.output.split("\n").filter((l) => l.trim() && !/ExperimentalWarning|trace-warnings|agent mode is in beta/.test(l)).slice(-12).join("\n");
    if (r.code !== 0 && !allowFail) throw new DemoError(`\`convex ${args[0]}\` failed:\n${output}${/download|fetch failed|ENOTFOUND|ECONNRESET|403/i.test(output) ? "\nThe first run downloads the local Convex backend from github.com; check the network connection." : ""}`);
    return { code: r.code, output };
  };

  // 2. Presenter key pair and agent secret, generated once on this computer.
  const existing = parseEnvFile(d.read(".env.local"));
  if (!KEYS.every((k) => existing.get(k))) {
    const keys = await generateDemoKeys();
    d.writePrivate(".env.local", appendEnv(d.read(".env.local"), { WAREORB_LOCAL_DEMO_PRIVATE_JWK: keys.privateJwk, WAREORB_LOCAL_DEMO_JWKS: keys.jwksDataUri, WAREORB_LOCAL_AGENT_SECRET: randomBytes(32).toString("hex") }));
    d.log("Generated the presenter's key pair and the agent secret in .env.local (private, git-ignored).");
  }

  // 3. The accountless local deployment (data in .convex/local) — created by the CLI, then re-checked.
  if (!pre.deployment) {
    d.log("Creating the local Convex deployment (first run)…");
    await convex(["dev", "--once", "--typecheck", "disable", "--tail-logs", "disable", ...localFlags], { allowFail: true });
    if (!parseEnvFile(d.read(".env.local")).get("CONVEX_DEPLOYMENT")) throw new DemoError("Could not create the local Convex deployment. See the output above; the first run needs github.com to download the backend.");
  }
  let target = localTarget(d.read(".env.local"), ports);
  const env = parseEnvFile(d.read(".env.local"));
  const secret = env.get("WAREORB_LOCAL_AGENT_SECRET")!;
  const privateJwk = env.get("WAREORB_LOCAL_DEMO_PRIVATE_JWK")!;
  await d.withSecretFile(
    [`WAREORB_LOCAL_DEMO_JWKS=${env.get("WAREORB_LOCAL_DEMO_JWKS")}`, `WAREORB_LOCAL_AGENT_URL=${agentUrl}`, `WAREORB_LOCAL_AGENT_SECRET=${secret}`, "WAREORB_ALLOW_DEMO_SEED=true"].join("\n"),
    (file) => convex(["env", "set", "--from-file", file, "--force"]),
  );
  d.log("Pushing WareOrb functions to the local backend…");
  await convex(["dev", "--once", "--typecheck", "disable", "--tail-logs", "disable", ...localFlags]);
  target = localTarget(d.read(".env.local"), ports);

  // 4. Keep the local backend running.
  const backend = d.start(["bunx", "convex", "dev", "--typecheck", "disable", "--tail-logs", "always", ...localFlags], cliEnv, ".convex/demo-backend.log");
  let web: LongProcess | null = null;
  const stop = () => { web?.kill(); backend.kill(); };
  try {
    const call = async (token: string | null, kind: "query" | "mutation", path: string, args: unknown): Promise<CallResult> => {
      const url = loopbackUrl(target.convexUrl, "CONVEX_URL", ports.convex);
      const res = await d.fetch(`${url}/api/${kind}`, {
        method: "POST",
        headers: { "Content-Type": "application/json", ...(token ? { Authorization: `Bearer ${token}` } : {}) },
        body: JSON.stringify({ path, args, format: "json" }),
      });
      return (await res.json()) as CallResult;
    };
    for (let i = 0; ; i++) {
      const r = await call(null, "query", "access:me", {}).catch(() => null);
      if (r?.status === "success") break;
      if (i > 120) throw new DemoError("The local backend did not become ready; see .convex/demo-backend.log");
      await d.sleep(500);
    }

    // 5. The presenter (owner) and the synthetic demo data, once; data then persists across restarts.
    const boot = await convex(["run", "access:bootstrapOwner", JSON.stringify({ tokenIdentifier: localDemoTokenIdentifier(LOCAL_DEMO_PRESENTER.subject), email: LOCAL_DEMO_PRESENTER.email, name: LOCAL_DEMO_PRESENTER.name })], { allowFail: true });
    if (boot.code !== 0 && !/already been provisioned/.test(boot.output)) throw new DemoError(`Could not create the presenter:\n${boot.output}`);
    const token = (await mintDemoToken(privateJwk, LOCAL_DEMO_PRESENTER, 300)).token;
    const snap = await call(token, "query", "ledger:snapshot", { since: 0 });
    if (snap.status !== "success") throw new DemoError(`The presenter could not read the ledger: ${JSON.stringify("errorData" in snap ? snap.errorData : snap.errorMessage)}`);
    const empty = !snap.value || (snap.value as { skus: unknown[] }).skus.length === 0;
    if (reset || empty) {
      await convex(["run", "seed:run"]);
      d.log(reset ? "Reloaded the synthetic demo data." : "Loaded the synthetic demo data (first run).");
    } else {
      d.log("Kept the existing local warehouse data (use --reset to reload the synthetic data).");
    }

    const webUrl = `http://127.0.0.1:${ports.web}`;
    if (setupOnly) {
      stop();
      d.log("Setup complete.");
      return { ports, convexUrl: target.convexUrl, siteUrl: target.siteUrl, webUrl, stop };
    }

    // 6. The WareOrb server with the presenter signed in (it reads no .env files of its own).
    const agentEnv = Object.fromEntries(AGENT_PASS.flatMap((k) => (d.ambient[k] ? [[k, d.ambient[k]!]] : [])));
    web = d.start(["bun", "--no-env-file", "src/index.ts"], childEnv(d.ambient, {
      ...agentEnv,
      NODE_ENV: "production",
      PORT: String(ports.web),
      WAREORB_LOCAL_DEMO: "1",
      BUN_PUBLIC_WAREORB_LOCAL_DEMO: "1",
      // Bun only inlines public variables that exist; the demo does not use Clerk.
      BUN_PUBLIC_CLERK_PUBLISHABLE_KEY: "",
      BUN_PUBLIC_CONVEX_URL: target.convexUrl,
      BUN_PUBLIC_CONVEX_SITE_URL: target.siteUrl,
      WAREORB_CONVEX_PORT: String(ports.convex),
      WAREORB_CONVEX_SITE_PORT: String(ports.convexSite),
      WAREORB_LOCAL_DEMO_PRIVATE_JWK: privateJwk,
      WAREORB_LOCAL_AGENT_SECRET: secret,
      PI_TELEMETRY: "0",
    }));
    const status = await d.agentStatus().catch((e) => ({ ready: false, reason: e instanceof Error ? e.message : "unknown error" }) as Awaited<ReturnType<DemoDeps["agentStatus"]>>);
    d.log(status.ready ? `Jarvis: connected to ${status.provider}/${status.model}${status.subscription ? " (subscription)" : ""}` : `Jarvis not connected yet: open the page and use Log in in Jarvis (${status.reason})`);
    d.log(`Open ${webUrl} — Ctrl+C stops the demo (data stays in .convex/local).`);
    return { ports, convexUrl: target.convexUrl, siteUrl: target.siteUrl, webUrl, web: web.exited, stop };
  } catch (e) {
    stop();
    throw e;
  }
}

