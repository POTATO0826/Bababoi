#!/usr/bin/env bun
// WareOrb local presentation: `bun run demo` (add `--reset` to reload the synthetic demo data).
// Everything runs on this computer: an accountless local Convex backend whose data persists in
// .convex/local, and the WareOrb server at http://127.0.0.1:3000 with the presenter signed in.
// The agent uses the operator's Pi login (`pi` → /login); without it, manual receiving still works.
import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, openSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { LOCAL_DEMO_PRESENTER, localDemoTokenIdentifier } from "../src/domain/local-demo";
import { generateDemoKeys, mintDemoToken } from "../src/local/demo-identity";

const root = join(import.meta.dir, "..");
const envPath = join(root, ".env.local");
const port = Number(process.env.WAREORB_DEMO_PORT ?? 3000);
const reset = process.argv.includes("--reset");
const setupOnly = process.argv.includes("--setup-only");

const log = (msg: string) => console.log(`[demo] ${msg}`);
function die(msg: string): never {
  console.error(`[demo] ${msg}`);
  process.exit(1);
}

function readEnv() {
  const values = new Map<string, string>();
  if (!existsSync(envPath)) return values;
  for (const line of readFileSync(envPath, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) values.set(m[1]!, m[2]!.replace(/^'(.*)'$/, "$1").replace(/^"(.*)"$/, "$1"));
  }
  return values;
}

function addEnv(entries: Record<string, string>) {
  const kept = (existsSync(envPath) ? readFileSync(envPath, "utf8") : "").split("\n").filter((l) => !Object.keys(entries).some((k) => l.startsWith(`${k}=`)));
  while (kept.length && !kept.at(-1)!.trim()) kept.pop();
  const lines = [...kept, "", "# WareOrb local demo (generated by scripts/demo.ts; private to this computer, never commit)", ...Object.entries(entries).map(([k, v]) => `${k}='${v}'`), ""];
  writeFileSync(envPath, lines.join("\n"), { mode: 0o600 });
  chmodSync(envPath, 0o600);
}

/** The local backend runs "use node" actions only on Node 20, 22 or 24. */
function convexNodeDir(): string {
  const which = Bun.which("node");
  const dirs = [which ? dirname(which) : "", "/opt/homebrew/opt/node@24/bin", "/opt/homebrew/opt/node@22/bin", "/opt/homebrew/opt/node@20/bin", "/usr/local/opt/node@24/bin", "/usr/local/opt/node@22/bin"];
  for (const dir of dirs.filter(Boolean)) {
    const bin = join(dir, "node");
    if (!existsSync(bin)) continue;
    const major = Number(Bun.spawnSync([bin, "--version"]).stdout.toString().trim().replace(/^v/, "").split(".")[0]);
    if ([20, 22, 24].includes(major)) return dir;
  }
  die("The local Convex backend needs Node.js 20, 22 or 24. Install it once with: brew install node@24");
}

const nodeDir = convexNodeDir();
const convexEnv = { ...process.env, PATH: `${nodeDir}:${process.env.PATH}`, CONVEX_AGENT_MODE: "anonymous" };

async function convex(args: string[], { allowFail = false } = {}) {
  const p = Bun.spawn(["bunx", "convex", ...args], { cwd: root, env: convexEnv, stdin: "ignore", stdout: "pipe", stderr: "pipe" });
  const [out, err] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text()]);
  const code = await p.exited;
  const output = `${out}\n${err}`.split("\n").filter((l) => l.trim() && !/ExperimentalWarning|trace-warnings|agent mode is in beta/.test(l)).slice(-12).join("\n");
  if (code !== 0 && !allowFail) die(`\`convex ${args[0]}\` failed:\n${output}`);
  return { code, output };
}

async function call(url: string, token: string | null, kind: "query" | "mutation", path: string, args: unknown) {
  const res = await fetch(`${url}/api/${kind}`, {
    method: "POST",
    headers: { "Content-Type": "application/json", ...(token ? { Authorization: `Bearer ${token}` } : {}) },
    body: JSON.stringify({ path, args, format: "json" }),
  });
  return (await res.json()) as { status: "success"; value: unknown } | { status: "error"; errorMessage: string; errorData?: unknown };
}

// 1. Never touch a cloud database from this checkout.
const deployment = readEnv().get("CONVEX_DEPLOYMENT");
if (deployment && !/^(anonymous|local):/.test(deployment)) {
  die(`.env.local selects ${deployment}, a cloud deployment. The demo only runs a local backend; use a separate checkout or move .env.local aside.`);
}

// 2. Presenter key pair and agent secret, generated once on this computer.
if (!["WAREORB_LOCAL_DEMO_PRIVATE_JWK", "WAREORB_LOCAL_DEMO_JWKS", "WAREORB_LOCAL_AGENT_SECRET"].every((k) => readEnv().get(k))) {
  const keys = await generateDemoKeys();
  addEnv({ WAREORB_LOCAL_DEMO_PRIVATE_JWK: keys.privateJwk, WAREORB_LOCAL_DEMO_JWKS: keys.jwksDataUri, WAREORB_LOCAL_AGENT_SECRET: randomBytes(32).toString("hex") });
  log("Generated the presenter's key pair and the agent secret in .env.local (private, git-ignored).");
}

// 3. Accountless local deployment (data in .convex/local) with the demo settings.
if (!readEnv().get("CONVEX_DEPLOYMENT")) {
  log("Creating the local Convex deployment (first run)…");
  await convex(["dev", "--once", "--typecheck", "disable", "--tail-logs", "disable"], { allowFail: true });
  if (!readEnv().get("CONVEX_DEPLOYMENT")) die("Could not create the local Convex deployment.");
}
const env = readEnv();
const tmp = mkdtempSync(join(tmpdir(), "wareorb-env-"));
try {
  const file = join(tmp, "backend.env");
  writeFileSync(file, [
    `WAREORB_LOCAL_DEMO_JWKS=${env.get("WAREORB_LOCAL_DEMO_JWKS")}`,
    `WAREORB_LOCAL_AGENT_URL=http://127.0.0.1:${port}`,
    `WAREORB_LOCAL_AGENT_SECRET=${env.get("WAREORB_LOCAL_AGENT_SECRET")}`,
    "WAREORB_ALLOW_DEMO_SEED=true",
  ].join("\n"), { mode: 0o600 });
  await convex(["env", "set", "--from-file", file, "--force"]);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
log("Pushing WareOrb functions to the local backend…");
await convex(["dev", "--once", "--typecheck", "disable", "--tail-logs", "disable"]);

// 4. Keep the local backend running.
const logDir = join(root, ".convex");
mkdirSync(logDir, { recursive: true });
const backendLog = openSync(join(logDir, "demo-backend.log"), "a");
const backend = Bun.spawn(["bunx", "convex", "dev", "--typecheck", "disable", "--tail-logs", "always"], { cwd: root, env: convexEnv, stdin: "ignore", stdout: backendLog, stderr: backendLog });
let web: ReturnType<typeof Bun.spawn> | null = null;
const stop = () => {
  web?.kill();
  backend.kill();
};
process.on("SIGINT", () => { stop(); process.exit(0); });
process.on("SIGTERM", () => { stop(); process.exit(0); });

const cloudUrl = readEnv().get("CONVEX_URL") ?? die("CONVEX_URL missing from .env.local");
const siteUrl = readEnv().get("CONVEX_SITE_URL") ?? die("CONVEX_SITE_URL missing from .env.local");
for (let i = 0; ; i++) {
  const r = await call(cloudUrl, null, "query", "access:me", {}).catch(() => null);
  if (r?.status === "success") break;
  if (i > 120) { stop(); die(`The local backend did not become ready; see .convex/demo-backend.log`); }
  await Bun.sleep(500);
}

// 5. The presenter (owner) and the synthetic demo data, once; data then persists across restarts.
const privateJwk = env.get("WAREORB_LOCAL_DEMO_PRIVATE_JWK")!;
const boot = await convex(["run", "access:bootstrapOwner", JSON.stringify({ tokenIdentifier: localDemoTokenIdentifier(LOCAL_DEMO_PRESENTER.subject), email: LOCAL_DEMO_PRESENTER.email, name: LOCAL_DEMO_PRESENTER.name })], { allowFail: true });
if (boot.code !== 0 && !/already been provisioned/.test(boot.output)) { stop(); die(`Could not create the presenter:\n${boot.output}`); }
const token = (await mintDemoToken(privateJwk, LOCAL_DEMO_PRESENTER, 300)).token;
const snap = await call(cloudUrl, token, "query", "ledger:snapshot", { since: 0 });
if (snap.status !== "success") { stop(); die(`The presenter could not read the ledger: ${JSON.stringify("errorData" in snap ? snap.errorData : snap.errorMessage)}`); }
const empty = !snap.value || (snap.value as { skus: unknown[] }).skus.length === 0;
if (reset || empty) {
  await convex(["run", "seed:run"]);
  log(reset ? "Reloaded the synthetic demo data." : "Loaded the synthetic demo data (first run).");
} else {
  log("Kept the existing local warehouse data (use --reset to reload the synthetic data).");
}

if (setupOnly) { stop(); log("Setup complete."); process.exit(0); }

// 6. The WareOrb server with the presenter signed in.
web = Bun.spawn(["bun", "src/index.ts"], {
  cwd: root,
  env: {
    ...process.env,
    NODE_ENV: "production",
    PORT: String(port),
    WAREORB_LOCAL_DEMO: "1",
    BUN_PUBLIC_WAREORB_LOCAL_DEMO: "1",
    BUN_PUBLIC_CONVEX_URL: cloudUrl,
    BUN_PUBLIC_CONVEX_SITE_URL: siteUrl,
    WAREORB_LOCAL_DEMO_PRIVATE_JWK: privateJwk,
    WAREORB_LOCAL_AGENT_SECRET: env.get("WAREORB_LOCAL_AGENT_SECRET")!,
    PI_TELEMETRY: "0",
  },
  stdin: "ignore",
  stdout: "inherit",
  stderr: "inherit",
});
const { agentStatus } = await import("../src/local/agent");
const status = await agentStatus();
log(status.ready ? `Agent: Pi · ${status.provider}/${status.model}${status.subscription ? " (subscription)" : ""}` : `Agent not connected: ${status.reason}`);
log(`Open http://127.0.0.1:${port} — Ctrl+C stops the demo (data stays in .convex/local).`);
await web.exited;
stop();
